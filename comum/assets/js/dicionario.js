  const TEXTOS = { pt, en, fr };

  function lingua(cod) {
    return LINGUAS.find((l) => l.cod === cod) || LINGUAS[0];
  }

  function original(cod, chave) {
    // Sem tradução na língua pedida, cai no português, que é a de origem.
    return (TEXTOS[cod] && TEXTOS[cod][chave]) !== undefined ? TEXTOS[cod][chave] : pt[chave];
  }

  function encher(bruto, valores) {
    if (!valores) return bruto;
    return bruto.replace(/\{(\w+)\}/g, (_, n) => (valores[n] === undefined ? '' : String(valores[n])));
  }

  // t('pt', 'erro.nome') -> o texto nessa língua. Os {marcadores} são trocados
  // pelos valores dados; o que não vier fica vazio. Uma chave que não exista
  // devolve o próprio nome da chave — é para quem não tem alternativa nenhuma
  // (texto montado em JavaScript), e à vista diz logo o que falta.
  function t(cod, chave, valores) {
    const bruto = original(cod, chave);
    return bruto === undefined ? chave : encher(bruto, valores);
  }

  // Como t(), mas devolve null quando a chave não existe — para quem tem um
  // original por baixo (o texto escrito no HTML) e prefere mantê-lo a
  // substituí-lo pelo nome da chave.
  function talvez(cod, chave, valores) {
    const bruto = original(cod, chave);
    return bruto === undefined ? null : encher(bruto, valores);
  }

  const DICIONARIO = { LINGUAS, TEXTOS, t, talvez, lingua, codigos: LINGUAS.map((l) => l.cod) };

